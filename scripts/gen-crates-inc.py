#!/usr/bin/env python3
"""Generate the Yocto crate list for cidint-cli from Cargo.lock.

Every third-party crate is listed with the SHA-256 recorded in
Cargo.lock, so the Yocto build fetches exactly what was tested.

    python scripts/gen-crates-inc.py            # rewrite the .inc file
    python scripts/gen-crates-inc.py --check    # exit 1 if it is stale
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "Cargo.lock"
OUT = ROOT / "meta-cidint/recipes-cidint/cidint-cli/cidint-cli-crates.inc"
REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"


def read_lock() -> list:
    """Parse the [[package]] tables of Cargo.lock.

    Cargo.lock is machine-written with one `key = "value"` per line, so a
    small parser is enough and works on Python older than 3.11 (no tomllib).
    """
    packages = []
    for block in LOCK.read_text(encoding="utf-8").split("[[package]]")[1:]:
        fields = dict(re.findall(r'^(\w+) = "([^"]*)"$', block, flags=re.M))
        if "name" not in fields or "version" not in fields:
            sys.exit(f"cannot parse Cargo.lock package entry: {block[:80]!r}")
        packages.append(fields)
    return packages


def render() -> str:
    packages = read_lock()
    crates = []
    for p in packages:
        source = p.get("source")
        if source is None:
            continue  # workspace member
        if source != REGISTRY or "checksum" not in p:
            sys.exit(f"{p['name']} {p['version']}: unsupported source {source!r}")
        crates.append((p["name"], p["version"], p["checksum"]))
    crates.sort()

    lines = ["# Autogenerated by scripts/gen-crates-inc.py from Cargo.lock. Do not edit.", ""]
    lines.append('SRC_URI += " \\')
    lines += [f"    crate://crates.io/{n}/{v} \\" for n, v, _ in crates]
    lines.append('"')
    lines.append("")
    lines += [f'SRC_URI[{n}-{v}.sha256sum] = "{c}"' for n, v, c in crates]
    return "\n".join(lines) + "\n"


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date; run scripts/gen-crates-inc.py")
        print("crate list matches Cargo.lock")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count('crate://')} crates)")


if __name__ == "__main__":
    main()
